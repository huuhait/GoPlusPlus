// Generates compiler/lib/Basic/UnicodeTables.inc: the ranges of Unicode letters
// (category L) and decimal digits (category Nd) that Go uses for identifiers,
// and of the runes Go's strconv.IsPrint calls printable (strconv.Quote writes
// every other rune as an escape). With -quote it writes
// tests/unit/Basic/GoQuote.inc instead: what strconv.Quote does with each code
// point, in ranges, which tests/unit/Basic/UnicodeTest.cpp checks every code
// point against.
// Usage (the repository has no go.mod, so name the file):
//
//	go run tools/gen-unicode/main.go > compiler/lib/Basic/UnicodeTables.inc
//	go run tools/gen-unicode/main.go -quote > tests/unit/Basic/GoQuote.inc
package main

import (
	"flag"
	"fmt"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

func ranges(name string, pred func(rune) bool) {
	fmt.Printf("static const uint32_t %s[][2] = {\n", name)
	start := rune(-1)
	n := 0
	flush := func(end rune) {
		fmt.Printf("{0x%X,0x%X},", start, end)
		n++
		if n%6 == 0 {
			fmt.Println()
		}
	}
	for r := rune(0x80); r <= unicode.MaxRune; r++ {
		if pred(r) {
			if start < 0 {
				start = r
			}
		} else if start >= 0 {
			flush(r - 1)
			start = -1
		}
	}
	if start >= 0 {
		flush(unicode.MaxRune)
	}
	fmt.Println("\n};")
}

// quoteClass says what strconv.Quote does with the code point r: 'P' writes
// it as it is, 'E' a backslash and a letter or the rune itself (\a ... \v,
// \", \\), 'X' \xNN, 'u' \uXXXX, 'U' \UXXXXXXXX; '-' is a surrogate, which no
// UTF-8 text holds.
func quoteClass(r rune) byte {
	if !utf8.ValidRune(r) {
		return '-'
	}
	s := string(r)
	q := strconv.Quote(s)
	body := q[1 : len(q)-1]
	switch {
	case body == s:
		return 'P'
	case strings.HasPrefix(body, `\x`):
		return 'X'
	case strings.HasPrefix(body, `\u`):
		return 'u'
	case strings.HasPrefix(body, `\U`):
		return 'U'
	case len(body) == 2 && body[0] == '\\':
		return 'E'
	}
	panic(fmt.Sprintf("strconv.Quote(%U) = %s", r, q))
}

func quoteDump() {
	fmt.Printf("// Generated by tools/gen-unicode -quote from Go's strconv.Quote (Unicode %s). Do not edit.\n", unicode.Version)
	fmt.Println("static const GoQuoteRange GoQuoteRanges[] = {")
	start, class, n := rune(0), quoteClass(0), 0
	flush := func(end rune) {
		fmt.Printf("{0x%X,0x%X,'%c'},", start, end, class)
		n++
		if n%5 == 0 {
			fmt.Println()
		}
	}
	for r := rune(1); r <= unicode.MaxRune; r++ {
		if c := quoteClass(r); c != class {
			flush(r - 1)
			start, class = r, c
		}
	}
	flush(unicode.MaxRune)
	fmt.Println("\n};")
}

func main() {
	quote := flag.Bool("quote", false, "write the strconv.Quote dump of the unit test")
	flag.Parse()
	if *quote {
		quoteDump()
		return
	}
	fmt.Printf("// Generated by tools/gen-unicode from Go's unicode and strconv packages (Unicode %s). Do not edit.\n", unicode.Version)
	ranges("LetterRanges", unicode.IsLetter)
	ranges("DigitRanges", unicode.IsDigit)
	ranges("PrintRanges", strconv.IsPrint)
}
