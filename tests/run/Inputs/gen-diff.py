#!/usr/bin/env python3
"""Generates the differential table of P04.04 (tests/run/diff-*.test).

Each program in Inputs/diff/ evaluates hundreds of small expressions over one
scalar type and the edge values of that type (minimum, maximum, -1, 0, 1,
powers of two, NaN, infinities, -0.0 ...), and prints every result with
println. The programs are valid Go and valid Go++, and the expected output is
what Go prints on standard error: Inputs/diff/<name>.out from `go run` on the
host (linux/amd64), and Inputs/diff/<name>.arm64.out from the same program
built by Go for linux/arm64 and run under qemu-aarch64, when that differs
(gc fuses x*y+z there, D4.12). The tests run only the Go++ side (they need
no Go); this script needs Go (and QEMU for the arm64 files):

    python3 gen-diff.py --write DIR            # (re)writes the programs
    python3 gen-diff.py --write DIR --go GO    # and their expected output

Out-of-range float to integer conversions are left out of the table: gc's
answer depends on the target (amd64 and arm64 differ), D4.12 says Go++
saturates, and core-sat.test has those cases with their own expected
output. A complex128 product whose result depends on which of its two
products gc fuses on arm64 (gc picks by SSA value order, which the source
does not decide) is not printed either: the generator computes both fusions
and keeps the pairs where they agree.
"""
import argparse
import os
import shutil
import subprocess
import sys
import tempfile

INTS = {
    # name: (bits, signed)
    "int8": (8, True), "int16": (16, True), "int32": (32, True),
    "int64": (64, True), "int": (64, True),
    "uint8": (8, False), "uint16": (16, False), "uint32": (32, False),
    "uint64": (64, False), "uint": (64, False), "uintptr": (64, False),
}
CONV_TARGETS = ["int8", "int16", "int32", "int64", "int", "uint8", "uint16",
                "uint32", "uint64", "uint", "uintptr"]


def int_values(bits, signed):
    if signed:
        lo, hi = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
        vals = [lo, lo + 1, -(1 << (bits // 2)), -100 if bits > 8 else -100,
                -2, -1, 0, 1, 2, 7, hi // 3, hi - 1, hi]
    else:
        hi = (1 << bits) - 1
        vals = [0, 1, 2, 3, 7, 100 if bits > 8 else 100, 1 << (bits // 2),
                (1 << (bits - 1)) - 1, 1 << (bits - 1), (1 << (bits - 1)) + 1,
                hi - 1, hi]
        vals = [v for v in vals if v <= hi]
    out = []
    for v in vals:
        if v not in out:
            out.append(v)
    return out


def lit(v, name=None):
    return str(v)


def int_program(name):
    bits, signed = INTS[name]
    vals = int_values(bits, signed)
    counts = sorted(set([0, 1, 2, 3, bits // 2, bits - 1, bits, bits + 1,
                         2 * bits, 255, 256, 1 << 31, (1 << 62), (1 << 64) - 1]))
    # (A shift count is any integer type; the table uses uint, and the
    # signed counts below use int8..int64 with non-negative values.)
    L = []
    L.append("package main\n")
    L.append("// Generated by tests/run/Inputs/gen-diff.py: all of %s.\n" % name)
    L.append("type T = %s\n" % name)
    L.append("var vals = [...]T{%s}" % ", ".join(lit(v) for v in vals))
    L.append("var cnt = [...]uint{%s}" % ", ".join(str(c) for c in counts))
    L.append("var cnt8 = [...]int8{0, 1, 5, 7, 8, 9, 63, 64, 127}")
    L.append("var cnt64 = [...]int64{0, 1, 63, 64, 65, 1 << 40}")
    L.append("var cntU8 = [...]uint8{0, 1, 5, 7, 8, 9, 63, 64, 255}")
    L.append("")
    L.append("func main() {")
    # binary operators over all ordered pairs
    L.append("\tfor i := 0; i < len(vals); i++ {")
    L.append("\t\tfor j := 0; j < len(vals); j++ {")
    L.append("\t\t\ta, b := vals[i], vals[j]")
    L.append("\t\t\tprintln(a+b, a-b, a*b, a&b, a|b, a^b, a&^b)")
    L.append("\t\t\tprintln(a == b, a != b, a < b, a <= b, a > b, a >= b)")
    L.append("\t\t\tif b != 0 {")
    L.append("\t\t\t\tprintln(a/b, a%b)")
    L.append("\t\t\t}")
    # compound assignment, incdec
    L.append("\t\t\tx := a")
    L.append("\t\t\tx += b")
    L.append("\t\t\tx -= a")
    L.append("\t\t\tx *= b")
    L.append("\t\t\tx ^= a")
    L.append("\t\t\tx |= b")
    L.append("\t\t\tx &^= a")
    L.append("\t\t\tx++")
    L.append("\t\t\ty := b")
    L.append("\t\t\ty--")
    L.append("\t\t\tif b != 0 {")
    L.append("\t\t\t\tz := a")
    L.append("\t\t\t\tz /= b")
    L.append("\t\t\t\tw := a")
    L.append("\t\t\t\tw %= b")
    L.append("\t\t\t\tprintln(z, w)")
    L.append("\t\t\t}")
    L.append("\t\t\tprintln(x, y)")
    L.append("\t\t}")
    L.append("\t}")
    # unary
    L.append("\tfor i := 0; i < len(vals); i++ {")
    L.append("\t\ta := vals[i]")
    L.append("\t\tprintln(-a, ^a, +a, a == a)")
    # constants-on-the-right forms: operators with constant operands
    L.append("\t\tprintln(a+1, a-1, a*3, a&1, a|2, a^7, a&^1, a<<1, a>>1, a<<3, a>>2)")
    L.append("\t\tprintln(a/2, a%2, a/3, a%3, a/7, a%7)")
    L.append("\t\tprintln(a < 1, a > 0, a == 0, a != 1)")
    L.append("\t}")
    # shifts by every class of count
    L.append("\tfor i := 0; i < len(vals); i++ {")
    L.append("\t\ta := vals[i]")
    L.append("\t\tfor k := 0; k < len(cnt); k++ {")
    L.append("\t\t\tc := cnt[k]")
    L.append("\t\t\tprintln(a<<c, a>>c)")
    L.append("\t\t\ts := a")
    L.append("\t\t\ts <<= c")
    L.append("\t\t\tt := a")
    L.append("\t\t\tt >>= c")
    L.append("\t\t\tprintln(s, t)")
    L.append("\t\t}")
    L.append("\t\tfor k := 0; k < len(cnt8); k++ {")
    L.append("\t\t\tprintln(a<<cnt8[k], a>>cnt8[k])")
    L.append("\t\t}")
    L.append("\t\tfor k := 0; k < len(cnt64); k++ {")
    L.append("\t\t\tprintln(a<<cnt64[k], a>>cnt64[k])")
    L.append("\t\t}")
    L.append("\t\tfor k := 0; k < len(cntU8); k++ {")
    L.append("\t\t\tprintln(a<<cntU8[k], a>>cntU8[k])")
    L.append("\t\t}")
    L.append("\t}")
    # conversions
    L.append("\tfor i := 0; i < len(vals); i++ {")
    L.append("\t\ta := vals[i]")
    for t in CONV_TARGETS:
        L.append("\t\tprintln(%s(a))" % t)
    L.append("\t\tprintln(float64(a), float32(a), complex(float64(a), 0), complex(float32(a), 1))")
    L.append("\t\tprintln(float64(int64(a)), float32(uint64(a)))")
    L.append("\t}")
    L.append("}")
    return "\n".join(L) + "\n"


FLOAT_VALUES = {
    "float64": ["0", "negz", "1", "-1", "0.5", "1.5", "-2.5", "3.14159265358979",
                "1e10", "1e-10", "1e300", "5e-324", "1.7976931348623157e308",
                "2.2250738585072014e-308", "9007199254740993", "inf", "-inf",
                "nan", "-1e300", "123456789.125", "0.1", "255.5", "-127.5"],
    "float32": ["0", "negz", "1", "-1", "0.5", "1.5", "-2.5", "3.14159265",
                "1e10", "1e-10", "1e38", "1e-45", "3.4028235e38",
                "1.17549435e-38", "16777217", "inf", "-inf", "nan", "-1e38",
                "123456.78", "0.1", "255.5", "-127.5"],
}
# In-range values for float -> integer conversion, by target width.
FLOAT_TO_INT = {
    "int8": ["0", "1", "-1", "1.9", "-1.9", "127.9", "-128.9", "100.5"],
    "uint8": ["0", "1", "1.9", "255.9", "200.5", "0.99"],
    "int16": ["0", "-1", "32767.5", "-32768.5", "1234.9"],
    "uint16": ["0", "65535.9", "40000.5"],
    "int32": ["0", "-1", "2147483647.5", "-2147483648.5", "123456.789"],
    "uint32": ["0", "4294967295.5", "3000000000.5"],
    "int64": ["0", "-1", "1e15", "-1e15", "4503599627370496.5", "9007199254740992"],
    "uint64": ["0", "1e15", "4503599627370496.5", "9007199254740992"],
    "int": ["0", "-1", "1e15", "-1e15", "123.99"],
    "uint": ["0", "1e15", "123.99"],
    "uintptr": ["0", "1e15", "123.99"],
}


def f32(v):
    import struct
    return struct.unpack("f", struct.pack("f", v))[0]


def in_range(name, target, text):
    """True if float(text) converted to T is inside the range of target."""
    v = float(text)
    if name == "float32":
        v = f32(v)
    bits, signed = INTS[target]
    lo = -(1 << (bits - 1)) if signed else 0
    hi = (1 << (bits - 1)) if signed else (1 << bits)
    t = int(v)  # truncation toward zero
    return lo <= t < hi and lo <= v < hi


def float_program(name):
    vals = FLOAT_VALUES[name]
    L = []
    L.append("package main\n")
    L.append("// Generated by tests/run/Inputs/gen-diff.py: all of %s.\n" % name)
    L.append("type T = %s\n" % name)
    L.append("var zero T")
    L.append("")
    L.append("func main() {")
    L.append("\tnegz := -zero")
    L.append("\tinf := 1 / zero")
    L.append("\tnan := zero / zero")
    L.append("\t_, _, _ = negz, inf, nan")
    L.append("\tvals := [...]T{%s}" % ", ".join(vals))
    L.append("\tfor i := 0; i < len(vals); i++ {")
    L.append("\t\ta := vals[i]")
    L.append("\t\tprintln(a, -a, +a, a == a, a != a, a < 1, a >= 1, a == 0, a > 0)")
    L.append("\t\tprintln(float32(a), float64(a), complex(a, 1), real(complex(a, -a)), imag(complex(1, a)))")
    L.append("\t\tprintln(a+1, a-1, a*2, a/2, a/3, a*a, 1/a, 2-a)")
    L.append("\t\tfor j := 0; j < len(vals); j++ {")
    L.append("\t\t\tb := vals[j]")
    L.append("\t\t\tprintln(a+b, a-b, a*b, a/b)")
    L.append("\t\t\tprintln(a == b, a != b, a < b, a <= b, a > b, a >= b)")
    L.append("\t\t\tx := a")
    L.append("\t\t\tx += b")
    L.append("\t\t\ty := a")
    L.append("\t\t\ty -= b")
    L.append("\t\t\tz := a")
    L.append("\t\t\tz *= b")
    L.append("\t\t\tw := a")
    L.append("\t\t\tw /= b")
    L.append("\t\t\tw++")
    L.append("\t\t\tx--")
    L.append("\t\t\tprintln(x, y, z, w)")
    L.append("\t\t}")
    L.append("\t}")
    # rounding of conversions and arithmetic in the type
    if name == "float32":
        L.append("\tvar f T = 16777216")
        L.append("\tprintln(f+1, f*f, f/3, T(0.1), float64(T(0.1)), T(1)/3, float64(T(1)/3))")
        L.append("\tvar d float64 = 1e300")
        L.append("\tprintln(T(d), T(-d), T(d*d), T(1e-300), T(5e-324), T(1.00000001), T(16777217.0*d/d))")
    else:
        L.append("\tvar f T = 9007199254740992")
        L.append("\tprintln(f+1, f*f, f/3, T(0.1), T(1)/3, float32(f), float32(1e300*f/f))")
    # float -> int in range
    for t, vs in FLOAT_TO_INT.items():
        vs = [v for v in vs if in_range(name, t, v)]
        L.append("\tin_%s := [...]T{%s}" % (t, ", ".join(vs)))
        L.append("\tfor k := 0; k < len(in_%s); k++ {" % t)
        L.append("\t\tv := in_%s[k]" % t)
        L.append("\t\tprintln(%s(v))" % t)
        L.append("\t}")
    # integer -> float of every width
    for t in CONV_TARGETS:
        L.append("\tfrom_%s := [...]%s{0, 1, 2, 100, 127}" % (t, t))
        L.append("\tfor k := 0; k < len(from_%s); k++ {" % t)
        L.append("\t\tv := from_%s[k]" % t)
        L.append("\t\tprintln(T(v), T(v)/2)")
        L.append("\t}")
    L.append("}")
    return "\n".join(L) + "\n"


def part_value(text):
    import math
    return {"0": 0.0, "negz": -0.0, "inf": math.inf, "-inf": -math.inf,
            "nan": math.nan}.get(text) if text in ("0", "negz", "inf", "-inf", "nan") \
        else float(text)


def fused_products_agree(a, b):
    """True if a*b (complex128) is the same whichever of the two products
    of each part gc's arm64 rules fuse: re = ac - bd, im = ad + bc."""
    import math
    import struct
    from fractions import Fraction

    def fma(x, y, z):
        try:
            return math.fma(x, y, z)
        except ValueError:
            return math.nan
        except OverflowError:
            exact = Fraction(x) * Fraction(y) + Fraction(z)
            return math.inf if exact > 0 else -math.inf

    def same(x, y):
        if math.isnan(x) or math.isnan(y):
            return math.isnan(x) and math.isnan(y)
        return struct.pack("<d", x) == struct.pack("<d", y)

    (ar, ai), (br, bi) = a, b
    re_right = fma(-ai, bi, ar * br)
    re_left = fma(ar, br, -(ai * bi))
    im_right = fma(ai, br, ar * bi)
    im_left = fma(ar, bi, ai * br)
    return same(re_right, re_left) and same(im_right, im_left)


def complex_program(name):
    ft = "float64" if name == "complex128" else "float32"
    comps = FLOAT_VALUES[ft]
    # a smaller set of real parts and imaginary parts
    parts = ["0", "negz", "1", "-2.5", "inf", "-inf", "nan",
             "1e300" if ft == "float64" else "1e30", "1e-300" if ft == "float64" else "1e-30"]
    L = []
    L.append("package main\n")
    L.append("// Generated by tests/run/Inputs/gen-diff.py: all of %s.\n" % name)
    L.append("type T = %s\n" % name)
    L.append("type F = %s\n" % ft)
    L.append("var zero F")
    L.append("")
    L.append("func main() {")
    L.append("\tnegz := -zero")
    L.append("\tinf := 1 / zero")
    L.append("\tnan := zero / zero")
    L.append("\t_, _, _ = negz, inf, nan")
    L.append("\tparts := [...]F{%s}" % ", ".join(parts))
    L.append("\tvar vals [%d]T" % (len(parts) * len(parts)))
    L.append("\tn := 0")
    L.append("\tfor i := 0; i < len(parts); i++ {")
    L.append("\t\tfor j := 0; j < len(parts); j++ {")
    L.append("\t\t\tvals[n] = complex(parts[i], parts[j])")
    L.append("\t\t\tn++")
    L.append("\t\t}")
    L.append("\t}")
    P = len(parts)
    picks = [0, 1, P + 1, P * 2 + 3, P * 3 + 4, P * 5 + 5, P * 6 + 6, P * 4 + 7, P * 7 + 2]
    L.append("\tsel := [...]T{%s}" % ", ".join("vals[%d]" % k for k in picks))
    # Which products are printed (all of them for complex64: its parts are
    # multiplied exactly in float64, so a fusion changes nothing).
    pv = [part_value(x) for x in parts]
    vals = [(pv[i], pv[j]) for i in range(P) for j in range(P)]
    ok = [name != "complex128" or fused_products_agree(vals[i], vals[k])
          for i in range(len(vals)) for k in picks]
    L.append("\tprod := [...]bool{%s}" % ", ".join("true" if x else "false" for x in ok))
    L.append("\tfor i := 0; i < len(vals); i++ {")
    L.append("\t\ta := vals[i]")
    L.append("\t\tprintln(a, -a, +a, real(a), imag(a), a == a, a != a, a == 0, a != 0)")
    L.append("\t\tprintln(a+1, a-1, a*2, a/2, a*1i, a/1i)")
    # (Go's division by a complex number with a NaN part and an infinite
    # part picks the sign of zero from the sign bit of the NaN, which the
    # hardware decides: amd64 and arm64 differ, so the table leaves it out.)
    L.append("\t\tif a == a {")
    L.append("\t\t\tprintln(1 / a)")
    L.append("\t\t}")
    L.append("\t\tprintln(complex128(a), complex64(a), complex(real(a), imag(a)) == a)")
    L.append("\t\tfor j := 0; j < len(sel); j++ {")
    L.append("\t\t\tb := sel[j]")
    L.append("\t\t\tprintln(a+b, a-b, a == b, a != b)")
    L.append("\t\t\tif prod[i*len(sel)+j] {")
    L.append("\t\t\t\tprintln(a * b)")
    L.append("\t\t\t}")
    L.append("\t\t\tif b == b {")
    L.append("\t\t\t\tprintln(a / b)")
    L.append("\t\t\t}")
    L.append("\t\t\tx := a")
    L.append("\t\t\tx += b")
    L.append("\t\t\ty := a")
    L.append("\t\t\ty -= b")
    L.append("\t\t\tz := a")
    L.append("\t\t\tif prod[i*len(sel)+j] {")
    L.append("\t\t\t\tz *= b")
    L.append("\t\t\t}")
    L.append("\t\t\tw := a")
    L.append("\t\t\tif b == b {")
    L.append("\t\t\t\tw /= b")
    L.append("\t\t\t}")
    L.append("\t\t\tprintln(x, y, z, w)")
    L.append("\t\t}")
    L.append("\t}")
    L.append("}")
    return "\n".join(L) + "\n"


def programs():
    p = {}
    for n in INTS:
        p["int_" + n] = int_program(n)
    for n in FLOAT_VALUES:
        p["float_" + n] = float_program(n)
    for n in ("complex64", "complex128"):
        p["complex_" + n] = complex_program(n)
    return p


def go_stderr(go, source, arm64=False):
    """Go's standard error for the program: `go run` on the host, or with
    arm64 the program built for linux/arm64 and run under qemu-aarch64."""
    env = dict(os.environ, GOFLAGS="-mod=mod", GO111MODULE="off", CGO_ENABLED="0")
    with tempfile.TemporaryDirectory() as d:
        with open(os.path.join(d, "main.go"), "w") as f:
            f.write(source)
        if arm64:
            r = subprocess.run([go, "build", "-o", "prog", "main.go"], cwd=d,
                               capture_output=True, timeout=300,
                               env=dict(env, GOARCH="arm64"))
            if r.returncode != 0:
                sys.exit("go build (arm64) failed:\n" + r.stderr.decode()[-2000:])
            r = subprocess.run(["qemu-aarch64", os.path.join(d, "prog")],
                               capture_output=True, timeout=300)
        else:
            r = subprocess.run([go, "run", "main.go"], cwd=d, capture_output=True,
                               timeout=300, env=env)
        if r.returncode != 0:
            sys.exit("the Go program failed:\n" + r.stderr.decode()[-2000:])
        return r.stderr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", required=True, help="the directory to write to")
    ap.add_argument("--go", help="the go command: also write the .out files")
    ap.add_argument("--only", help="only this program")
    a = ap.parse_args()
    os.makedirs(a.write, exist_ok=True)
    for name, src in programs().items():
        if a.only and a.only != name:
            continue
        with open(os.path.join(a.write, name + ".gopp"), "w") as f:
            f.write(src)
        if a.go:
            out = go_stderr(a.go, src)
            with open(os.path.join(a.write, name + ".out"), "wb") as f:
                f.write(out)
            alt = os.path.join(a.write, name + ".arm64.out")
            arm = go_stderr(a.go, src, arm64=True) if shutil.which("qemu-aarch64") else None
            if arm is not None and arm != out:
                with open(alt, "wb") as f:
                    f.write(arm)
            elif arm is not None and os.path.exists(alt):
                os.remove(alt)
            print(name, len(src), "bytes of source,", len(out), "bytes of output",
                  "(arm64 differs)" if arm is not None and arm != out else "")


if __name__ == "__main__":
    main()
