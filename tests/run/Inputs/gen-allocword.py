#!/usr/bin/env python3
"""Writes the generated programs of tests/run/Inputs/allocword/ (P04.25,
ADR-0029).

usage: gen-allocword.py DIR

Every program uses the test intrinsics (`gopp build -test-intrinsics`,
docs/design/gir.md section 15): a slice made in the counting allocator 1, and
the counters of both allocators. For each element type the program grows the
slice by 700 single appends and by one append of a spread slice, and proves
that each growth is one `alloc` call of allocator 1 and no call of the global
allocator, that the slice keeps its word, that its elements are intact, and
that freeing it is one `free` call of allocator 1. The element types are those
of gen-coll.py (every size class of Go's allocator, with and without pointers,
zero-size elements) and the Go++ types whose size changed in ADR-0029: a string
(24 bytes), a slice (32), a map (8) and structs of them.

The programs are Go++ only (the intrinsics are not Go), so the expected output
is written here: one `ok NAME` line per type.
"""
import os
import sys

# (name, Go type, zero expression)
SCALAR = [
    ("u8", "byte", "0"),
    ("i16", "int16", "0"),
    ("b3", "[3]byte", "[3]byte{}"),
    ("i32", "int32", "0"),
    ("b5", "[5]byte", "[5]byte{}"),
    ("b6", "[6]byte", "[6]byte{}"),
    ("b7", "[7]byte", "[7]byte{}"),
    ("i64", "int", "0"),
    ("b12", "[12]byte", "[12]byte{}"),
    ("i32x3", "[3]int32", "[3]int32{}"),
    ("b16", "[16]byte", "[16]byte{}"),
    ("i64x3", "[3]int", "[3]int{}"),
    ("b40", "[40]byte", "[40]byte{}"),
    ("i64x5", "[5]int", "[5]int{}"),
    ("i64x10", "[10]int", "[10]int{}"),
    ("b100", "[100]byte", "[100]byte{}"),
    ("i64x33", "[33]int", "[33]int{}"),
    ("b513", "[513]byte", "[513]byte{}"),
    ("i64x200", "[200]int", "[200]int{}"),
    ("empty", "struct{}", "struct{}{}"),
    ("c128", "complex128", "0"),
    ("f32", "float32", "0"),
    ("bool", "bool", "false"),
    ("padded", "struct{ a int8; b int64; c int16 }", "struct{ a int8; b int64; c int16 }{}"),
]


def ptrs(n):
    return "[%d]*int{%s}" % (n, ", ".join(["&dummy"] * n))


POINTER = [
    ("ptr", "*int", "&dummy"),
    ("ptr2", "[2]*int", ptrs(2)),
    ("ptr3", "[3]*int", ptrs(3)),
    ("ptr5", "[5]*int", ptrs(5)),
    ("ptr10", "[10]*int", ptrs(10)),
    ("ptr64", "[64]*int", ptrs(64)),
    ("ptr65", "[65]*int", ptrs(65)),
    ("ptr200", "[200]*int", ptrs(200)),
    ("sp", "struct{ p *int; a int }", "struct{ p *int; a int }{&dummy, 1}"),
    ("sbig", "struct{ p *int; b [100]byte }", "struct{ p *int; b [100]byte }{p: &dummy}"),
    ("sbig2", "struct{ b [600]byte; p *int }", "struct{ b [600]byte; p *int }{p: &dummy}"),
    # The Go++ types of ADR-0029 and ADR-0026: a string is 24 bytes, a slice
    # 32, a map 8; a slice that holds slices grows in its own allocator, and
    # the slices inside it keep theirs.
    ("string", "string", '"x"'),
    ("slice", "[]int", "nil"),
    ("slices2", "[2][]byte", "[2][]byte{}"),
    ("map", "map[string]int", "nil"),
    ("sstr", "struct{ s string; n int }", 'struct{ s string; n int }{"y", 1}'),
    ("sslice", "struct{ n int8; xs []int16 }", "struct{ n int8; xs []int16 }{}"),
]


# Elements that own memory: `append(s, b...)` of them needs move(b) or
# b.Clone() (OWN-R4, P04.09), so these skip the spread phase.
OWNING = {"string", "slice", "slices2", "map", "sstr", "sslice"}


def program(title, types):
    out = ["package main", "", "// " + title,
           "// Generated by Inputs/gen-allocword.py; the expected output is the",
           "// generator's (the intrinsics are not Go). Build with -test-intrinsics.",
           "", "var dummy int", ""]
    for n, t, z in types:
        out.append('@Extern("C") func gopp_test_make_slice_%s(which int, n int, c int) []%s' % (n, t))
        out.append('@Extern("C") func gopp_test_free_slice_%s(s []%s)' % (n, t))
        out.append('@Extern("C") func gopp_test_word_%s(s []%s) int' % (n, t))
        out.append('@Extern("C") func gopp_test_clone_slice_%s(s []%s) []%s' % (n, t, t))
    out.append('@Extern("C") func gopp_test_count(which int, what int) int')
    out.append("")
    out.append("""// allocs(which) and frees(which): the calls of allocator `which` so far.
func allocs(which int) int { return gopp_test_count(which, 0) }
func frees(which int) int  { return gopp_test_count(which, 2) }
""")
    for n, t, z in types:
        spread = "" if n in OWNING else """// One append of many elements: one growth at most.
	s = append(s, big...)
	if cap(s) != before {
		grows++
	}
	"""
        mkbig = "" if n in OWNING else """big := make([]%s, 0, 300)
	for k := 0; k < 300; k++ {
		big = append(big, z)
	}
	""" % t
        total = 703 if n in OWNING else 1003
        out.append(f"""func case_{n}() {{
	var z {t} = {z}
	{mkbig}	g0, a0, f0 := allocs(0), allocs(1), frees(1)
	gf0 := frees(0)
	s := gopp_test_make_slice_{n}(1, 0, 0)
	grows := 1
	last := cap(s)
	for k := 0; k < 700; k++ {{
		s = append(s, z)
		if cap(s) != last {{
			last = cap(s)
			grows++
		}}
	}}
	before := cap(s)
	{spread}// Several values in one append.
	before = cap(s)
	s = append(s, z, z, z)
	if cap(s) != before {{
		grows++
	}}
	ok := len(s) == {total} && gopp_test_word_{n}(s) == 1
	if allocs(1)-a0 != grows || allocs(0) != g0 || frees(0) != gf0 {{
		println("FAIL {n}: alloc calls", allocs(1)-a0, "want", grows, "global", allocs(0)-g0, frees(0)-gf0)
		return
	}}
	if !ok {{
		println("FAIL {n}: len", len(s), "word", gopp_test_word_{n}(s))
		return
	}}
	// A clone stays in the allocator of the slice (SLC-3).
	c := gopp_test_clone_slice_{n}(s)
	if len(c) != {total} || gopp_test_word_{n}(c) != 1 || allocs(1)-a0 != grows+1 || allocs(0) != g0 {{
		println("FAIL {n}: clone", len(c), gopp_test_word_{n}(c), allocs(1)-a0, allocs(0)-g0)
		return
	}}
	// Freeing the slices is a free of allocator 1 and no free of the global one.
	gopp_test_free_slice_{n}(c)
	gopp_test_free_slice_{n}(s)
	if frees(1)-f0 != 2 || frees(0) != gf0 {{
		println("FAIL {n}: free calls", frees(1)-f0, frees(0)-gf0)
		return
	}}
	println("ok {n}")
}}
""")
    out.append("func main() {")
    for n, t, z in types:
        out.append(f"\tcase_{n}()")
    out.append("}")
    return "\n".join(out) + "\n"


def expected(types):
    return "".join("ok %s\n" % n for n, _, _ in types)


def main():
    d = sys.argv[1]
    os.makedirs(d, exist_ok=True)
    for name, title, types in (
        ("aw_append_scalar", "append growth in a second allocator: element types without pointers", SCALAR),
        ("aw_append_pointer", "append growth in a second allocator: element types with pointers", POINTER),
    ):
        with open(os.path.join(d, name + ".gopp"), "w") as f:
            f.write(program(title, types))
        with open(os.path.join(d, name + ".out"), "w") as f:
            f.write(expected(types))


main()
