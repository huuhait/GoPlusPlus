#!/usr/bin/env python3
"""Writes the generated programs of tests/run/Inputs/coll/ (P04.05).

usage: gen-coll.py DIR

The append-growth programs print the capacity `append` gives, for many
element types: every size class of Go's allocator is crossed, with and
without pointers in the element (Go rounds the new size up differently when
the element has a pointer and the array is over 512 bytes: a malloc header),
by one-at-a-time appends, by appends of slices of many lengths, and by the
conversions that make slices from strings. The slices live in package
variables so Go's escape analysis cannot put them on the stack (a small
append that does not escape starts in a 32 byte stack buffer).

The programs are valid Go and valid Go++. The expected output is `go run`'s
(gen-goldens.py --go GO --dir DIR DIR/*.gopp).
"""
import os
import sys

# (name, Go type, zero expression, has a pointer)
SCALAR = [
    ("u8", "byte", "0", False),
    ("i16", "int16", "0", False),
    ("b3", "[3]byte", "[3]byte{}", False),
    ("i32", "int32", "0", False),
    ("b5", "[5]byte", "[5]byte{}", False),
    ("b6", "[6]byte", "[6]byte{}", False),
    ("b7", "[7]byte", "[7]byte{}", False),
    ("i64", "int", "0", False),
    ("b12", "[12]byte", "[12]byte{}", False),
    ("i32x3", "[3]int32", "[3]int32{}", False),
    ("b16", "[16]byte", "[16]byte{}", False),
    ("i64x3", "[3]int", "[3]int{}", False),
    ("b40", "[40]byte", "[40]byte{}", False),
    ("i64x5", "[5]int", "[5]int{}", False),
    ("i64x10", "[10]int", "[10]int{}", False),
    ("b100", "[100]byte", "[100]byte{}", False),
    ("i64x33", "[33]int", "[33]int{}", False),
    ("b513", "[513]byte", "[513]byte{}", False),
    ("i64x200", "[200]int", "[200]int{}", False),
    ("empty", "struct{}", "struct{}{}", False),
    ("c128", "complex128", "0", False),
    ("f32", "float32", "0", False),
]
# a pointer has no nil in Go++: the elements point at a package variable
def ptrs(n):
    return "[%d]*int{%s}" % (n, ", ".join(["&dummy"] * n))


POINTER = [
    ("ptr", "*int", "&dummy", True),
    ("ptr2", "[2]*int", ptrs(2), True),
    ("ptr3", "[3]*int", ptrs(3), True),
    ("ptr5", "[5]*int", ptrs(5), True),
    ("ptr10", "[10]*int", ptrs(10), True),
    ("ptr63", "[63]*int", ptrs(63), True),
    ("ptr64", "[64]*int", ptrs(64), True),
    ("ptr65", "[65]*int", ptrs(65), True),
    ("ptr70", "[70]*int", ptrs(70), True),
    ("ptr200", "[200]*int", ptrs(200), True),
    ("sp", "struct{ p *int; a int }", "struct{ p *int; a int }{&dummy, 1}", True),
    ("sp3", "struct{ a, b int; c *int }", "struct{ a, b int; c *int }{1, 2, &dummy}", True),
    ("sbig", "struct{ p *int; b [100]byte }", "struct{ p *int; b [100]byte }{p: &dummy}", True),
    ("sbig2", "struct{ b [600]byte; p *int }", "struct{ b [600]byte; p *int }{p: &dummy}", True),
]
# A Go++ string is 24 bytes (ptr, len, cap) and an owned slice 32 (ptr, len,
# cap, allocator; ADR-0029), Go's are 16 and 24: the capacity of a []string and
# of a [][]int differs from Go's by design. The expected output is Go's for a
# type of the same size that holds a pointer.
STRINGS = [
    ("str", "string", '"x"', True),
    ("strs", "[]int", "nil", True),
]
STANDIN = [
    ("str", "struct{ p *int; a, b int }", "struct{ p *int; a, b int }{}", True),
    ("strs", "struct{ p *int; a, b, c int }", "struct{ p *int; a, b, c int }{}", True),
]


def single(name, typ, zero):
    return f"""var s_{name} []{typ}

func one_{name}() {{
	println("{name}")
	last := -1
	for i := 1; i <= {{N}}; i++ {{
		s_{name} = append(s_{name}, {zero})
		if cap(s_{name}) != last {{
			last = cap(s_{name})
			println(i, last)
		}}
	}}
	s_{name} = nil
}}
"""


BIG = ("200", "513", "600", "ptr63", "ptr64", "ptr65", "ptr70", "i64x33", "b100", "sbig", "i64x10", "ptr10")


def bulk(name, typ, zero):
    # nothing is freed before P04.09: a wide element gets a short table
    tables = ("bigcaps", "bigadds") if name in BIG or any(b in name for b in BIG) else ("caps", "adds")
    return f"""var b_{name} []{typ}

func bulk_{name}() {{
	println("bulk", "{name}")
	for _, c := range {tables[0]} {{
		for _, n := range {tables[1]} {{
			xs := make([]{typ}, 0, c)
			for i := 0; i < c; i++ {{
				xs = append(xs, {zero})
			}}
			ys := make([]{typ}, 0, n)
			for i := 0; i < n; i++ {{
				ys = append(ys, {zero})
			}}
			b_{name} = append(xs, ys...)
			println(c, n, len(b_{name}), cap(b_{name}))
		}}
	}}
	b_{name} = nil
}}
"""


def program(title, types, with_bulk, n_single, small_n=False):
    out = ["package main", "", f"// {title}", "// Generated by Inputs/gen-coll.py; the expected output is `go run`'s.", ""]
    out.append("var dummy int")
    out.append("")
    if with_bulk:
        out.append("var caps = []int{0, 1, 2, 3, 4, 5, 7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64, 65, 100, 127, 128, 255, 256, 257, 300, 511, 512, 513}")
        out.append("var adds = []int{1, 2, 3, 5, 8, 17, 100, 129, 255, 256, 600}")
        out.append("var bigcaps = []int{0, 1, 2, 3, 5, 8, 17, 33, 65, 129}")
        out.append("var bigadds = []int{1, 3, 17, 100, 129}")
        out.append("")
    for name, typ, zero, _ in types:
        n = n_single
        # a big element: fewer appends
        if "200" in typ or "513" in typ or "600" in typ or "70]" in typ:
            n = max(40, n_single // 4)
        out.append(single(name, typ, zero).replace("{N}", str(n)))
        if with_bulk:
            out.append(bulk(name, typ, zero))
    out.append("func main() {")
    for name, typ, zero, _ in types:
        out.append(f"	one_{name}()")
        if with_bulk:
            out.append(f"	bulk_{name}()")
    out.append("}")
    return "\n".join(out) + "\n"


FROM_STRINGS = '''package main

// The capacity of the slices that conversions and append make from strings
// and bytes: []byte(s) and []rune(s) (Go rounds up to a size class),
// append(bytes, string...), and make and literals (exact).
// Generated by Inputs/gen-coll.py; the expected output is `go run`'s.

var sb []byte
var sr []rune
var sx []int

func main() {
	text := "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
	long := ""
	for i := 0; i < 70; i++ {
		long += "abcdefghij"
	}
	for n := 0; n <= 130; n++ {
		sb = []byte(long[:n])
		sr = []rune(long[:n])
		println(n, len(sb), cap(sb), len(sr), cap(sr))
	}
	for _, n := range []int{255, 256, 257, 511, 512, 513, 600, 700} {
		sb = []byte(long[:n])
		sr = []rune(long[:n])
		println(n, len(sb), cap(sb), len(sr), cap(sr))
	}
	sb = nil
	for i := 0; i < 600; i++ {
		sb = append(sb, text...)
		println(i, len(sb), cap(sb))
		if i > 40 {
			break
		}
	}
	for n := 0; n < 40; n++ {
		sx = make([]int, n)
		sb = make([]byte, n, n+n/2)
		println(n, cap(sx), cap(sb))
	}
	lit := []int{1, 2, 3}
	sx = lit
	println(len(sx), cap(sx))
	sx = append(sx, 4)
	println(len(sx), cap(sx))
	sx = append(sx, 5, 6, 7, 8, 9, 10, 11, 12, 13)
	println(len(sx), cap(sx))
}
'''


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    progs = {
        "append_scalar": program("append growth: element types without pointers", SCALAR, True, 2500),
        "append_pointer": program("append growth: element types with pointers", POINTER, True, 2500),
        "append_string": program("append growth: strings and slices as elements", STRINGS, False, 2500),
    }
    for name, text in progs.items():
        with open(os.path.join(out, name + ".gopp"), "w") as f:
            f.write(text)
    # Go's side of append_string: gen-goldens.py runs it, and the expected
    # output is copied to coll/append_string.out (see the test)
    sd = os.path.join(os.path.dirname(out.rstrip("/")), "coll-standin")
    os.makedirs(sd, exist_ok=True)
    with open(os.path.join(sd, "append_string.gopp"), "w") as f:
        f.write(program("append growth: the stand-in of strings and slices (24 and 32 bytes, with a pointer)", STANDIN, False, 2500))
    with open(os.path.join(out, "append_convert.gopp"), "w") as f:
        f.write(FROM_STRINGS)


main()
