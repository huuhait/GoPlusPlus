def shift_program(name, bits, signed):
    T = name
    L = [HEADER % ("shifts of " + T)]
    L.append("type T = %s\n" % T)
    L.append("const bits = %d\n" % bits)
    L.append("var edges = [...]T{%s}\n" % ", ".join(lit(v) for v in edge_values(bits, signed)))
    L.append("""func mix(h uint64, v T) uint64 { return (h ^ uint64(v)) * 1099511628211 }

//go:noinline
func byCount(x T, n uint) (T, T) { return x << n, x >> n }

//go:noinline
func byCount8(x T, n uint8) (T, T) { return x << n, x >> n }

//go:noinline
func byCount16(x T, n uint16) (T, T) { return x << n, x >> n }

//go:noinline
func byCount32(x T, n uint32) (T, T) { return x << n, x >> n }

//go:noinline
func byCount64(x T, n uint64) (T, T) { return x << n, x >> n }

//go:noinline
func byCountI8(x T, n int8) (T, T) { return x << n, x >> n }

//go:noinline
func byCountI16(x T, n int16) (T, T) { return x << n, x >> n }

//go:noinline
func byCountI32(x T, n int32) (T, T) { return x << n, x >> n }

//go:noinline
func byCountI64(x T, n int64) (T, T) { return x << n, x >> n }

//go:noinline
func byCountInt(x T, n int) (T, T) { return x << n, x >> n }

// A constant operand with a variable count: 1 << n and -1 >> n.
//
//go:noinline
func constOperand(n uint) (T, T, T) { return 1 << n, T(3) << n, T(100) >> n }

// A count the optimizer can see: all the constants up to the width.
//
//go:noinline
func constCount(x T) uint64 {
	var h uint64
	h = mix(h, x<<0)
	h = mix(h, x<<1)
	h = mix(h, x<<(bits-1))
	h = mix(h, x>>0)
	h = mix(h, x>>1)
	h = mix(h, x>>(bits-1))
	h = mix(h, x<<(bits/2))
	h = mix(h, x>>(bits/2))
	return h
}

func main() {
	var h uint64 = 14695981039346656037
	for k := 0; k < len(edges); k++ {
		x := edges[k]
		h = mix(h, T(constCount(x)))
		// A loop the optimizer can unroll: the counts run past the width.
		for n := uint(0); n < 130; n++ {
			l, r := byCount(x, n)
			h = mix(h, l)
			h = mix(h, r)
			h = mix(h, x<<n)
			h = mix(h, x>>n)
			l, r = byCount8(x, uint8(n))
			h = mix(h, l)
			h = mix(h, r)
			l, r = byCount16(x, uint16(n))
			h = mix(h, l)
			h = mix(h, r)
			l, r = byCount32(x, uint32(n))
			h = mix(h, l)
			h = mix(h, r)
			l, r = byCount64(x, uint64(n))
			h = mix(h, l)
			h = mix(h, r)
			if n < 128 {
				l, r = byCountI8(x, int8(n))
				h = mix(h, l)
				h = mix(h, r)
			}
			l, r = byCountI16(x, int16(n))
			h = mix(h, l)
			h = mix(h, r)
			l, r = byCountI32(x, int32(n))
			h = mix(h, l)
			h = mix(h, r)
			l, r = byCountI64(x, int64(n))
			h = mix(h, l)
			h = mix(h, r)
			l, r = byCountInt(x, int(n))
			h = mix(h, l)
			h = mix(h, r)
		}
		println("x", x, h)
	}
	// Huge counts.
	for k := 0; k < len(edges); k++ {
		x := edges[k]
		var big uint64 = 1<<64 - 1
		l, r := byCount64(x, big)
		l2, r2 := byCount64(x, 1<<63)
		l3, r3 := byCount32(x, 1<<31)
		println("big", x, l, r, l2, r2, l3, r3)
	}
	for n := uint(0); n < 130; n += 7 {
		a, b, c := constOperand(n)
		println("const", n, a, b, c)
	}
	// Compound assignment.
	for n := uint(0); n < 130; n += 3 {
		for k := 0; k < len(edges); k++ {
			s := edges[k]
			t := edges[k]
			s <<= n
			t >>= n
			h = mix(h, s)
			h = mix(h, t)
		}
	}
	println("end", h)
}
""")
    return "".join(L)


