def edge_values(bits, signed):
    hi = (1 << bits) - 1
    if signed:
        lo, mx = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
        vals = [lo, lo + 1, lo + 2, -100, -7, -3, -2, -1, 0, 1, 2, 3, 5, 7,
                64, 100, mx // 2, mx - 1, mx]
    else:
        vals = [0, 1, 2, 3, 5, 7, 64, 100, hi >> 2, (1 << (bits - 1)) - 1,
                1 << (bits - 1), (1 << (bits - 1)) + 1, hi - 2, hi - 1, hi]
    out = []
    for v in vals:
        if v not in out and (lo if signed else 0) <= v <= (mx if signed else hi):
            out.append(v)
    return out


def lit(v):
    return str(v)


