def divedge_program(name, bits, signed):
    T = name
    L = [HEADER % ("division and remainder of " + T)]
    L.append("type T = %s\n" % T)
    L.append("const bits = %d\n" % bits)
    L.append("var edges = [...]T{%s}\n" % ", ".join(lit(v) for v in edge_values(bits, signed)))
    L.append("""func mix(h uint64, v T) uint64 { return (h ^ uint64(v)) * 1099511628211 }

//go:noinline
func divide(a, b T) T { return a / b }

//go:noinline
func remain(a, b T) T { return a % b }

//go:noinline
func divRem(a, b T) (T, T) { return a / b, a % b }
""")
    if signed:
        L.append("""// The one signed overflow: the most negative value over -1.
var minusOne T = -1

//go:noinline
func overByConst(a T) (T, T) { return a / -1, a % -1 }

//go:noinline
func overByVar(a T) (T, T) { return a / minusOne, a % minusOne }

//go:noinline
func negDivPow2(a T) (T, T, T, T, T, T) { return a / 2, a % 2, a / 4, a % 4, a / 64, a % 64 }

//go:noinline
func negDivOther(a T) (T, T, T, T, T, T) { return a / 3, a % 3, a / -3, a % -3, a / 10, a % -10 }

//go:noinline
func identity(a, b T) bool { return (a/b)*b+a%b == a }
""")
    else:
        L.append("""//go:noinline
func divConsts(a T) (T, T, T, T, T, T) { return a / 3, a % 3, a / 7, a % 7, a / 10, a % 10 }

//go:noinline
func identity(a, b T) bool { return (a/b)*b+a%b == a }
""")
    L.append("""func main() {
	var h uint64 = 14695981039346656037
""")
    if bits <= 8:
        L.append("""	for i := 0; i < 1<<bits; i++ {
		a := T(i)
""")
        if signed:
            L.append("""		x, y := overByConst(a)
		h = mix(mix(h, x), y)
		x, y = overByVar(a)
		h = mix(mix(h, x), y)
		p, q, r, s, t, u := negDivPow2(a)
		h = mix(mix(mix(mix(mix(mix(h, p), q), r), s), t), u)
		p, q, r, s, t, u = negDivOther(a)
		h = mix(mix(mix(mix(mix(mix(h, p), q), r), s), t), u)
""")
        else:
            L.append("""		p, q, r, s, t, u := divConsts(a)
		h = mix(mix(mix(mix(mix(mix(h, p), q), r), s), t), u)
""")
        L.append("""		for j := 0; j < 1<<bits; j++ {
			b := T(j)
			if b == 0 {
				continue
			}
			d, m := divRem(a, b)
			h = mix(mix(h, d), m)
			if !identity(a, b) {
				println("identity fails", a, b)
			}
		}
	}
	println("all", h)
""")
    else:
        L.append("""	for i := 0; i < len(edges); i++ {
		a := edges[i]
""")
        if signed:
            L.append("""		x, y := overByConst(a)
		println("byConst", a, x, y)
		x, y = overByVar(a)
		println("byVar", a, x, y)
		p, q, r, s, t, u := negDivPow2(a)
		println("pow2", a, p, q, r, s, t, u)
		p, q, r, s, t, u = negDivOther(a)
		println("other", a, p, q, r, s, t, u)
""")
        else:
            L.append("""		p, q, r, s, t, u := divConsts(a)
		println("consts", a, p, q, r, s, t, u)
""")
        L.append("""		for j := 0; j < len(edges); j++ {
			b := edges[j]
			if b == 0 {
				continue
			}
			d, m := divRem(a, b)
			println("divrem", a, b, d, m, identity(a, b))
		}
	}
	var s uint64 = 88172645463325252
	for i := 0; i < 20000; i++ {
		s ^= s << 13
		s ^= s >> 7
		s ^= s << 17
		a, b := T(s), T(s>>(s&31))
		if b == 0 {
			continue
		}
		d, m := divRem(a, b)
		h = mix(mix(h, d), m)
""")
        if signed:
            L.append("""		x, y := overByVar(a)
		h = mix(mix(h, x), y)
		p, q, r, s2, t, u := negDivOther(a)
		h = mix(mix(mix(mix(mix(mix(h, p), q), r), s2), t), u)
""")
        L.append("""	}
	println("all", h)
""")
    L.append("}\n")
    return "".join(L)


