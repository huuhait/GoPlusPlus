#!/usr/bin/env python3
"""Generates the stress set of P04.13 (tests/run/core-opt-*.test).

Every program is built to give an optimizer a chance to use "undefined
behaviour" that Go defines, or to drop a check Go keeps. Go++ must print what
Go prints, at every `opt` level and with `-pipeline=fastisel`:

  wrap-<T>      wrapping arithmetic in loops (no `nsw`/`nuw` may be used:
                `i+1 > i`, `x*2/2 == x`, `-x == x`, counters that wrap and end
                a loop), exhaustive for 8 bits, sampled for the wider types;
                every operator over edge values, divisors and shift counts
                that are constants (the optimizer sees them) and variables;
  shift-<T>     shifts by every count 0..130 of every count type, constant and
                variable, in loops the optimizer can unroll;
  divedge-<T>   signed division and remainder edges: MinInt / -1, MinInt % -1,
                negative dividends by powers of two and by other constants
                (the optimizer's magic numbers), all pairs for 8 bits;
  float-<T>     NaN, -0.0 and infinities through the identities an optimizer
                with fast-math flags would use (`x*0`, `x+0`, `x-x`, `x != x`,
                `!(x < y)` against `x >= y`, `0-x` against `-x`);
  conv          integer <-> float conversions that fit, and their rounding;
  memory        locals that must be zero in every iteration or call, swaps,
                overlapping assignments, aliasing, bit casts through unsafe;
  sat           float to integer conversions that do not fit (saturate, D4.12):
                gc's answers differ by target, so there is no Go golden; the
                matrix compares every level with the baseline;
  panics/opt-*  checks that must stay: an unused division, an unused index, a
                check in a loop after output, an index that wrapped.

The programs are valid Go and valid Go++. Their expected output is what Go
prints to standard error: Inputs/opt/NAME.out from `go run` on the host and
Inputs/opt/NAME.arm64.out from Go's arm64 build under QEMU when that differs
(gc fuses x*y+z there). The tests run only the Go++ side. This script needs Go
and QEMU:

    python3 gen-opt.py --write DIR                 # the programs
    python3 gen-opt.py --write DIR --go GO         # and their expected output

DIR is tests/run/Inputs. The programs are small to read as text and big to run:
the 8-bit tables go over all 65536 pairs.
"""
