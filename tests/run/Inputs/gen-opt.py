# Wrapping arithmetic.


def wrap_program(name, bits, signed):
    T = name
    L = [HEADER % ("wrapping arithmetic of " + T)]
    L.append("type T = %s\n" % T)
    L.append("const bits = %d\n" % bits)
    L.append("var edges = [...]T{%s}\n" % ", ".join(lit(v) for v in edge_values(bits, signed)))
    L.append("""func mix(h uint64, v T) uint64 { return (h ^ uint64(v)) * 1099511628211 }

// The wrap of a counter ends these loops. With `nsw` the optimizer may call
// them infinite or assume the exit never happens.
//
//go:noinline
func countUp(start T) int {
	n := 0
	for i := start; i >= start; i++ {
		n++
		if n > 70000 {
			break
		}
	}
	return n
}

//go:noinline
func countDown(start T) int {
	n := 0
	for i := start; i <= start; i-- {
		n++
		if n > 70000 {
			break
		}
	}
	return n
}

//go:noinline
func wrapStep(start T, step T) int {
	n := 0
	for i := start; i != start-step || n == 0; i += step {
		n++
		if n > 70000 {
			break
		}
	}
	return n
}

// Checks an optimizer folds when it believes overflow cannot happen.
//
//go:noinline
func incGreater(x T) bool { return x+1 > x }

//go:noinline
func addLess(x, y T) bool { return x+y < x }

//go:noinline
func doubleHalf(x T) bool { return x*2/2 == x }

//go:noinline
func negSame(x T) bool { return -x == x }

//go:noinline
func shiftBack(x T) bool { return x<<1>>1 == x }

//go:noinline
func subLess(x, y T) bool { return x-y < x }

//go:noinline
func mulBigger(x T) bool { return x*3 > x }

//go:noinline
func constChecks(x T) (bool, bool, bool, bool) {
	return x+1 > x, x-1 < x, x+100 > x, x*2 > x
}
""")
    # operator table over a pair
    L.append("""//go:noinline
func ops(h uint64, a, b T) uint64 {
	h = mix(h, a+b)
	h = mix(h, a-b)
	h = mix(h, a*b)
	h = mix(h, a&b)
	h = mix(h, a|b)
	h = mix(h, a^b)
	h = mix(h, a&^b)
	h = mix(h, -a)
	h = mix(h, ^a)
	if a < b {
		h = mix(h, 1)
	}
	if a <= b {
		h = mix(h, 2)
	}
	if a == b {
		h = mix(h, 3)
	}
	if b != 0 {
		h = mix(h, a/b)
		h = mix(h, a%b)
	}
	h = mix(h, a<<(uint8(b)&127))
	h = mix(h, a>>(uint8(b)&127))
	return h
}

// The same operations with constant operands: the optimizer rewrites them
// (multiplications into shifts and adds, divisions into magic numbers).
//
//go:noinline
func consts(h uint64, a T) uint64 {
	h = mix(h, a+1)
	h = mix(h, a-1)
	h = mix(h, a*3)
	h = mix(h, a*7+5)
	h = mix(h, a/2)
	h = mix(h, a%2)
	h = mix(h, a/3)
	h = mix(h, a%3)
	h = mix(h, a/7)
	h = mix(h, a%7)
	h = mix(h, a/10)
	h = mix(h, a%10)
	h = mix(h, a/64)
	h = mix(h, a%64)
	h = mix(h, a<<1)
	h = mix(h, a>>1)
	h = mix(h, a<<3)
	h = mix(h, a>>2)
	h = mix(h, a&0x55)
	h = mix(h, a|0x0f)
	h = mix(h, a^0x33)
	return h
}

func main() {
	var h uint64 = 14695981039346656037
	// Counters that wrap.
	for k := 0; k < len(edges); k++ {
		println("count", edges[k], countUp(edges[k]), countDown(edges[k]))
	}
	println("step", wrapStep(0, 1), wrapStep(3, 1), wrapStep(edges[len(edges)-1], 1))
	// The checks, at the edges.
	for k := 0; k < len(edges); k++ {
		x := edges[k]
		a, b, c, d := constChecks(x)
		println("chk", x, incGreater(x), doubleHalf(x), negSame(x), shiftBack(x), mulBigger(x), a, b, c, d)
		for j := 0; j < len(edges); j++ {
			y := edges[j]
			println("chk2", x, y, addLess(x, y), subLess(x, y))
		}
	}
""")
    if bits <= 8:
        L.append("""	// All of the type.
	for i := 0; i < 1<<bits; i++ {
		a := T(i)
		h = consts(h, a)
		for j := 0; j < 1<<bits; j++ {
			h = ops(h, a, T(j))
		}
	}
	println("all", h)
""")
    elif bits == 16:
        L.append("""	// All dividends against the edge values and a sample of the rest.
	for i := 0; i < 1<<bits; i++ {
		a := T(i)
		h = consts(h, a)
		for j := 0; j < len(edges); j++ {
			h = ops(h, a, edges[j])
		}
		h = ops(h, a, T(i*257+13))
	}
	println("all", h)
""")
    else:
        L.append("""	// Edge values against each other, then a sequence from a generator.
	for i := 0; i < len(edges); i++ {
		h = consts(h, edges[i])
		for j := 0; j < len(edges); j++ {
			h = ops(h, edges[i], edges[j])
		}
	}
	var s uint64 = 88172645463325252
	for i := 0; i < 20000; i++ {
		s ^= s << 13
		s ^= s >> 7
		s ^= s << 17
		a := T(s)
		b := T(s >> 21)
		h = consts(h, a)
		h = ops(h, a, b)
		h = ops(h, a, T(s>>(s&63)))
	}
	println("all", h)
""")
    L.append("""	// A multiply-add generator: the wrap is part of the algorithm.
	var seed T = 12345 % 100
	for i := 0; i < 1000; i++ {
		seed = seed*5 + 1
		h = mix(h, seed)
	}
	var acc T
	for i := T(0); i < 100; i++ {
		acc += i * i * i
		acc -= i << 3
	}
	println("lcg", seed, acc, h)
}
""")
    return "".join(L)


