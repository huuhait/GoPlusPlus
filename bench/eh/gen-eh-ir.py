#!/usr/bin/env python3
"""Generate Go++-shaped LLVM IR for the exception-handling cost spike (P04.15).

The IR is what an `-O0`, plain-pipeline Go++ compiler emits (D4.2, D4.4, D4.5,
D4.6), in Clang's -O0 style (every local in an alloca, no PHIs):

  * owning locals (`string`, slices; 24 bytes) are zeroed at entry and dropped
    on every exit and on unwind (drop glue skips all-zero values, D4.2);
  * calls that may unwind while something must be dropped are `invoke`s with a
    cleanup landing pad (personality `__gxx_personality_v0`, D4.6);
  * bounds, division, type-assertion and nil checks branch to a cold
    `noreturn` panic call, itself an `invoke` when something must be dropped;
  * functions with `defer` get a catch-all pad that runs the deferred call,
    asks the runtime about `recover` and rethrows (D4.6);
  * small structs pass by value and `(T, error)` returns come back in
    registers (D4.4).

The program is drawn once from --seed and the rates measured on Go code by
bench/eh/goshape.go (see RATES); --mode and --abi only change how it is
written, so every variant is the same program:

  --mode eh      invokes, landing pads, a personality (D4.6)
  --mode noeh    the same calls as plain calls, no pads, every function
                 `nounwind` (what `-panic=abort` emits; the cost of EH)
  --mode shape   the same CFG and the same cleanup code as `eh`, with the
                 EH instructions replaced by plain ones (a call plus a
                 two-way branch for `invoke`, loads for `landingpad`, a call
                 for `resume`): what a FastISel that handled EH would see
  --abi agg      first-class aggregates: `{i64, i64}` arguments, `{i64, i64}`
                 and `{i64, {ptr, ptr}}` returns (D4.4: in registers)
  --abi split    scalars only: struct arguments split into fields, aggregate
                 results through a hidden out pointer
  --pads chain   one landing pad per cleanup depth, chained cleanup blocks
                 (Clang's layout)
  --pads single  one landing pad per function that drops every owner (they
                 are zeroed at entry, so dropping an unused one is a no-op);
                 NOT the exact drop order, kept only for comparison
  --pads state   one landing pad per function; each unwinding site first
                 stores a cleanup-state index, and the pad dispatches on it
                 (compare and branch) into the same per-scope cleanup
                 chains as `chain`, so the drop order is exact (ADR-0028
                 decision 3.2)
  --panics each  one panic call per check (as Go does)
  --panics shared  one panic call per function, panic kind and cleanup
                 state; the checks store the operands and branch to it

Writes the module to stdout and its shape (counts and rates) to stderr.

  python3 bench/eh/gen-eh-ir.py --mode eh > eh.ll
"""
import argparse
import random
import sys

# Per source line of Go code, measured by bench/eh/goshape.go on 22 standard
# library packages (3663 functions, 64983 body lines); see ADR-0028.
RATES = {
    "call": 0.171,  # a call that may unwind (89% of calls)
    "ncall": 0.021,  # a call to a body that cannot unwind
    "builtin": 0.054,  # len/cap/append/make/copy: half inline, half runtime
    "bounds": 0.057,  # index or slice expression on a slice/string/array
    "assert": 0.0042,  # x.(T) without comma-ok
    "div": 0.0004,  # integer division by a non-constant
    "nil": 0.0003,  # method call on an `error` value (Go++ nil check)
    "owner": 0.046,  # a new owning local
    "if": 0.112,  # an if statement
    "loop": 0.019,  # a for or range loop
}
# Per call: share of calls whose argument is an owning temporary (f(g()),
# f(a+b)); tuned so that the generated programs (seeds 1 to 3) match the share of
# unwinding sites that need a pad measured on Go (58.5% of calls and checks).
# Owners live at such a site: 2.0 to 2.2 generated, 2.56 measured.
P_TEMP = 0.25
# Function signatures: shares of call sites in the measurement.
P_RET_TERR = 0.095  # (T, error) result: 1185 of 12491 calls
P_RET_PAIR = 0.076  # other multi or small-struct results: 951 of 12491
P_RET_I64 = 0.40
P_PAIR_PARAM = 0.05  # takes a small struct: 586 of 12491 calls pass one
P_DEFER = 0.072  # functions with defer: 264 of 3663
# Body lines: quantiles of the measured distribution (p10 3, p25 4, p50 9,
# p75 19, p90 41, p99 137).
SIZE_QUANTILES = [(0.0, 1), (0.10, 3), (0.25, 4), (0.50, 9), (0.75, 19),
                  (0.90, 41), (0.99, 137), (1.0, 300)]

PRELUDE = """\
; Go++-shaped IR for the P04.15 EH cost spike; generated by bench/eh/gen-eh-ir.py
target triple = "{triple}"

%string = type {{ ptr, i64, i64 }}
%iface = type {{ ptr, ptr }}
%pair = type {{ i64, i64 }}
%terr = type {{ i64, %iface }}

@gslice = global %string zeroinitializer
@itab.T = external constant ptr
@gopp.fake = global i1 false
@gopp.seed = global i64 0
@gopp.seedif = global %iface zeroinitializer

declare i32 @__gxx_personality_v0(...)
declare ptr @__cxa_begin_catch(ptr) nounwind
declare void @__cxa_end_catch(){eh_attr}
declare void @__cxa_rethrow(){rethrow_attr}
declare void @llvm.memset.p0.i64(ptr, i8, i64, i1)
declare void @llvm.memcpy.p0.p0.i64(ptr, ptr, i64, i1)
declare void @gopp.string.drop(ptr) nounwind
declare void @gopp.string.concat(ptr, ptr, i64, ptr, i64) nounwind
declare ptr @gopp.makeslice(i64) nounwind
declare i1 @gopp.recovered(ptr) nounwind
declare void @gopp.fake.resume(ptr, i32) noreturn nounwind
declare void @gopp.panicIndex(i64, i64) noreturn cold{panic_attr}
declare void @gopp.panicDivide() noreturn cold{panic_attr}
declare void @gopp.panicAssert(ptr, ptr) noreturn cold{panic_attr}
declare void @gopp.panicNil() noreturn cold{panic_attr}
"""


def sample_size(rng):
    u = rng.random()
    for (q0, v0), (q1, v1) in zip(SIZE_QUANTILES, SIZE_QUANTILES[1:]):
        if u <= q1:
            return max(1, round(v0 + (v1 - v0) * (u - q0) / (q1 - q0)))
    return SIZE_QUANTILES[-1][1]


class Fn:
    pass


def make_program(rng, source_lines, n_leaf):
    """Draw the abstract program: signatures first, then body events."""
    fns = []
    total = 0
    while total < source_lines:
        f = Fn()
        f.idx = len(fns)
        f.lines = sample_size(rng)
        total += f.lines
        r = rng.random()
        f.ret = ("terr" if r < P_RET_TERR else
                 "pair" if r < P_RET_TERR + P_RET_PAIR else
                 "i64" if r < P_RET_TERR + P_RET_PAIR + P_RET_I64 else "void")
        f.nstr = rng.choice([0, 0, 1, 1, 1, 2])  # borrowed string/slice params
        f.nint = rng.choice([0, 1, 1, 2, 2, 3])
        f.pair_param = rng.random() < P_PAIR_PARAM
        f.has_defer = rng.random() < P_DEFER
        fns.append(f)
    for f in fns:
        ev = []
        open_blocks = []  # remaining lines of each open if/loop
        for _ in range(f.lines):
            for kind in ("if", "loop"):
                if rng.random() < RATES[kind] and len(open_blocks) < 4:
                    k = 1 + int(rng.expovariate(1 / 3))
                    ev.append((kind,))
                    open_blocks.append(k)
            if rng.random() < RATES["owner"]:
                ev.append(("owner",))
            if rng.random() < RATES["call"]:
                callee = rng.randrange(len(fns))
                ev.append(("call", callee, rng.random() < P_TEMP))
            if rng.random() < RATES["ncall"]:
                ev.append(("ncall", rng.randrange(n_leaf)))
            if rng.random() < RATES["builtin"]:
                ev.append(("builtin", rng.random() < 0.5))
            for kind in ("bounds", "assert", "div", "nil"):
                if rng.random() < RATES[kind]:
                    ev.append((kind,))
            ev.append(("plain", rng.randrange(4)))
            # close blocks that ended
            closing = 0
            for i in range(len(open_blocks)):
                open_blocks[i] -= 1
            while open_blocks and open_blocks[-1] <= 0:
                open_blocks.pop()
                closing += 1
            ev.extend([("end",)] * closing)
        ev.extend([("end",)] * len(open_blocks))
        f.events = ev
    return fns


class Emitter:
    """Renders one function body in the chosen mode and ABI."""

    def __init__(self, fns, mode, abi, pads, panics, stats):
        self.fns, self.mode, self.abi, self.pads, self.panics = fns, mode, abi, pads, panics
        self.st = stats

    def sig(self, f):
        """(return type, [param types]) of f under the ABI."""
        params = []
        if self.abi == "split" and f.ret in ("terr", "pair"):
            params.append("ptr")  # hidden out pointer
        params += ["ptr", "i64"] * f.nstr + ["i64"] * f.nint
        if f.pair_param:
            params += ["%pair"] if self.abi == "agg" else ["i64", "i64"]
        if self.abi == "split" and f.ret in ("terr", "pair"):
            ret = "void"
        else:
            ret = {"terr": "%terr", "pair": "%pair", "i64": "i64", "void": "void"}[f.ret]
        return ret, params

    # -- small helpers -------------------------------------------------------
    def v(self):
        self.nv += 1
        return "%%t%d" % self.nv

    def label(self, base):
        self.nl += 1
        return "%s%d" % (base, self.nl)

    def out(self, s):
        self.body.append("  " + s)

    def block(self, name):
        self.body.append(name + ":")

    def int_local(self):
        return "%%i%d" % self.rng.randrange(self.nints)

    def unwinding(self):
        """Is something to be dropped (or a defer to run) right now?"""
        return self.f.has_defer or bool(self.owners)

    def pad_for(self, temp):
        """The landing pad an unwinding site at this point goes to."""
        f = self.f
        if f.has_defer:
            return "dpad"
        if self.pads == "single":
            self.need_single = True
            return "lpad.all"
        chain = self.cleanup(tuple(self.owners))
        if self.pads == "state":
            # one landing pad; the site stores which cleanup to start at
            target = chain
            if temp is not None:
                target = self.label("cleanup.tmp")
                self.temp_pads.append((target, temp, chain))
            if target not in self.states:
                self.states[target] = len(self.states)
            if self.mode != "noeh":
                self.out("store i32 %d, ptr %%eh.state" % self.states[target])
            return "lpad.state"
        if temp is not None:
            name = self.label("lpad.tmp")
            self.temp_pads.append((name, temp, chain))
            return name
        if chain not in self.lpads:
            self.lpads[chain] = self.label("lpad")
        return self.lpads[chain]

    def cleanup(self, live):
        """The cleanup block that drops `live` (innermost last), then resumes.
        Stacks that share a prefix share the rest of the chain (Clang)."""
        if live not in self.chains:
            self.chains[live] = self.label("cleanup")
            if live:
                self.cleanup(live[:-1])
        return self.chains[live]

    def call_site(self, ret, callee, args, temp=None, noreturn=False):
        """A call that may unwind: `invoke` when something must be dropped."""
        argstr = ", ".join("%s %s" % a for a in args)
        dst = "" if ret == "void" else self.v() + " = "
        if not self.unwinding() and temp is None:
            self.out("%scall %s %s(%s)" % (dst, ret, callee, argstr))
            if noreturn:
                self.out("unreachable")
            self.st["calls_plain"] += 1
            return dst[:-3] if dst else None
        pad = self.pad_for(temp)
        self.st["invokes"] += 1
        self.st["live_at_invoke"] += len(self.owners) + (1 if temp is not None else 0) + (1 if self.f.has_defer else 0)
        cont = self.label("noreturn" if noreturn else "cont")
        if self.mode == "eh":
            self.out("%sinvoke %s %s(%s)" % (dst, ret, callee, argstr))
            self.out("        to label %%%s unwind label %%%s" % (cont, pad))
        elif self.mode == "shape":
            self.out("%scall %s %s(%s)" % (dst, ret, callee, argstr))
            self.out("br i1 %%fake, label %%%s, label %%%s" % (pad, cont))
        else:  # noeh: no pads at all
            self.out("%scall %s %s(%s)" % (dst, ret, callee, argstr))
            if noreturn:
                self.out("unreachable")
            return dst[:-3] if dst else None
        self.block(cont)
        if noreturn:
            self.out("unreachable")
        return dst[:-3] if dst else None

    def string_arg(self):
        """(ptr, len) of a borrowed string: a parameter, an owner or a global."""
        srcs = ["%%sp%d" % i for i in range(self.f.nstr)] + \
            ["%%o%d" % i for i in self.owners]
        src = self.rng.choice(srcs) if srcs else "@gslice"
        return self.load_string(src)

    def load_string(self, src):
        p = self.v()
        self.out("%s = getelementptr inbounds %%string, ptr %s, i32 0, i32 0" % (p, src))
        ptr = self.v()
        self.out("%s = load ptr, ptr %s" % (ptr, p))
        q = self.v()
        self.out("%s = getelementptr inbounds %%string, ptr %s, i32 0, i32 1" % (q, src))
        ln = self.v()
        self.out("%s = load i64, ptr %s" % (ln, q))
        return ptr, ln

    def load_int(self):
        x = self.v()
        self.out("%s = load i64, ptr %s" % (x, self.int_local()))
        return x

    def panic_check(self, cond_ok, callee, args):
        ok = self.label("ok")
        self.st["panic_sites"] += 1
        if self.panics == "shared":
            # one panic call per kind and cleanup state; the operands go
            # through two slots
            key = (callee, self.pad_for(None) if self.unwinding() and self.mode != "noeh" else None)
            if key not in self.shared:
                self.shared[key] = self.label("panic.shared")
            for (ty, val), slot in zip(args, ("%pslot0", "%pslot1")):
                self.out("store %s %s, ptr %s" % (ty, val, slot))
            self.out("br i1 %s, label %%%s, label %%%s, !prof !0" % (cond_ok, ok, self.shared[key]))
            self.block(ok)
            return
        fail = self.label("panic")
        self.out("br i1 %s, label %%%s, label %%%s, !prof !0" % (cond_ok, ok, fail))
        self.block(fail)
        self.call_site("void", callee, args, noreturn=True)
        self.block(ok)

    def shared_panics(self):
        """The shared panic blocks of --panics shared."""
        nargs = {"@gopp.panicIndex": 2, "@gopp.panicAssert": 2}
        for (callee, pad), name in self.shared.items():
            self.block(name)
            if pad is not None:
                self.st["invokes"] += 1
            args = []
            for k in range(nargs.get(callee, 0)):
                ty = "i64" if callee == "@gopp.panicIndex" else "ptr"
                x = self.v()
                self.out("%s = load %s, ptr %%pslot%d" % (x, ty, k))
                args.append((ty, x))
            argstr = ", ".join("%s %s" % a for a in args)
            if pad is None:
                self.st["calls_plain"] += 1
                self.out("call void %s(%s)" % (callee, argstr))
                self.out("unreachable")
            elif self.mode == "eh":
                cont = self.label("noreturn")
                self.out("invoke void %s(%s)" % (callee, argstr))
                self.out("        to label %%%s unwind label %%%s" % (cont, pad))
                self.block(cont)
                self.out("unreachable")
            else:  # shape
                cont = self.label("noreturn")
                self.out("call void %s(%s)" % (callee, argstr))
                self.out("br i1 %%fake, label %%%s, label %%%s" % (pad, cont))
                self.block(cont)
                self.out("unreachable")

    # -- events --------------------------------------------------------------
    def ev_call(self, callee_idx, temp):
        g = self.fns[callee_idx]
        ret, _ = self.sig(g)
        args = []
        tmp = None
        if self.abi == "split" and g.ret in ("terr", "pair"):
            args.append(("ptr", "%outt" if g.ret == "terr" else "%outp"))
        for k in range(g.nstr):
            if k == 0 and temp:  # f(a + b): an owning temporary argument
                tmp = "%%tmp%d" % self.ntemps
                self.ntemps += 1
                a, al = self.string_arg()
                b, bl = self.string_arg()
                self.out("call void @gopp.string.concat(ptr %s, ptr %s, i64 %s, ptr %s, i64 %s)"
                         % (tmp, a, al, b, bl))
                p, ln = self.load_string(tmp)
            else:
                p, ln = self.string_arg()
            args += [("ptr", p), ("i64", ln)]
        for _ in range(g.nint):
            args.append(("i64", self.load_int()))
        if g.pair_param:
            a, b = self.load_int(), self.load_int()
            if self.abi == "agg":
                p1 = self.v()
                self.out("%s = insertvalue %%pair poison, i64 %s, 0" % (p1, a))
                p2 = self.v()
                self.out("%s = insertvalue %%pair %s, i64 %s, 1" % (p2, p1, b))
                args.append(("%pair", p2))
            else:
                args += [("i64", a), ("i64", b)]
            self.st["struct_args"] += 1
        res = self.call_site(ret, "@f%d" % callee_idx, args, temp=tmp)
        self.st["calls"] += 1
        if tmp is not None:
            self.out("call void @gopp.string.drop(ptr %s)" % tmp)
        # use the result
        if g.ret == "i64":
            self.out("store i64 %s, ptr %s" % (res, self.int_local()))
        elif g.ret == "pair":
            self.st["agg_results"] += 1
            if self.abi == "agg":
                x = self.v()
                self.out("%s = extractvalue %%pair %s, 0" % (x, res))
            else:
                p = self.v()
                self.out("%s = getelementptr inbounds %%pair, ptr %%outp, i32 0, i32 0" % p)
                x = self.v()
                self.out("%s = load i64, ptr %s" % (x, p))
            self.out("store i64 %s, ptr %s" % (x, self.int_local()))
        elif g.ret == "terr":
            self.st["agg_results"] += 1
            if self.abi == "agg":
                x = self.v()
                self.out("%s = extractvalue %%terr %s, 0" % (x, res))
                e = self.v()
                self.out("%s = extractvalue %%terr %s, 1, 0" % (e, res))
                d = self.v()
                self.out("%s = extractvalue %%terr %s, 1, 1" % (d, res))
            else:
                p = self.v()
                self.out("%s = getelementptr inbounds %%terr, ptr %%outt, i32 0, i32 0" % p)
                x = self.v()
                self.out("%s = load i64, ptr %s" % (x, p))
                q = self.v()
                self.out("%s = getelementptr inbounds %%terr, ptr %%outt, i32 0, i32 1, i32 0" % q)
                e = self.v()
                self.out("%s = load ptr, ptr %s" % (e, q))
                q2 = self.v()
                self.out("%s = getelementptr inbounds %%terr, ptr %%outt, i32 0, i32 1, i32 1" % q2)
                d = self.v()
                self.out("%s = load ptr, ptr %s" % (d, q2))
            self.out("store i64 %s, ptr %s" % (x, self.int_local()))
            # if err != nil { return ..., err }
            c = self.v()
            self.out("%s = icmp ne ptr %s, null" % (c, e))
            ret_err = self.label("reterr")
            cont = self.label("noerr")
            self.out("br i1 %s, label %%%s, label %%%s" % (c, ret_err, cont))
            self.block(ret_err)
            if self.f.ret == "terr":
                self.out("store ptr %s, ptr %%ret.itab" % e)
                self.out("store ptr %s, ptr %%ret.data" % d)
            self.out("br label %exit")
            self.block(cont)

    def ev_bounds(self):
        srcs = ["%%sp%d" % i for i in range(self.f.nstr)] + \
            ["%%o%d" % i for i in self.owners]
        src = self.rng.choice(srcs) if srcs else "@gslice"
        ptr, ln = self.load_string(src)
        i = self.load_int()
        c = self.v()
        self.out("%s = icmp ult i64 %s, %s" % (c, i, ln))
        self.panic_check(c, "@gopp.panicIndex", [("i64", i), ("i64", ln)])
        p = self.v()
        self.out("%s = getelementptr inbounds i8, ptr %s, i64 %s" % (p, ptr, i))
        b = self.v()
        self.out("%s = load i8, ptr %s" % (b, p))
        w = self.v()
        self.out("%s = zext i8 %s to i64" % (w, b))
        self.out("store i64 %s, ptr %s" % (w, self.int_local()))
        self.st["bounds"] += 1

    def ev_iface_check(self, kind):
        p = self.v()
        self.out("%s = getelementptr inbounds %%iface, ptr %%if, i32 0, i32 0" % p)
        it = self.v()
        self.out("%s = load ptr, ptr %s" % (it, p))
        c = self.v()
        if kind == "assert":
            self.out("%s = icmp eq ptr %s, @itab.T" % (c, it))
            self.panic_check(c, "@gopp.panicAssert", [("ptr", it), ("ptr", "@itab.T")])
        else:
            self.out("%s = icmp ne ptr %s, null" % (c, it))
            self.panic_check(c, "@gopp.panicNil", [])

    def ev_div(self):
        a, b = self.load_int(), self.load_int()
        c = self.v()
        self.out("%s = icmp ne i64 %s, 0" % (c, b))
        self.panic_check(c, "@gopp.panicDivide", [])
        q = self.v()
        self.out("%s = sdiv i64 %s, %s" % (q, a, b))
        self.out("store i64 %s, ptr %s" % (q, self.int_local()))

    def ev_plain(self, k):
        a = self.load_int()
        r = self.v()
        if k == 0:
            self.out("%s = add i64 %s, %d" % (r, a, self.rng.randrange(1, 100)))
        elif k == 1:
            b = self.load_int()
            self.out("%s = mul i64 %s, %s" % (r, a, b))
        elif k == 2:
            c = self.v()
            self.out("%s = icmp slt i64 %s, %d" % (c, a, self.rng.randrange(100)))
            self.out("%s = select i1 %s, i64 %s, i64 0" % (r, c, a))
        else:  # the length of a borrowed string parameter or a global
            src = "%sp0" if self.f.nstr else "@gslice"
            p = self.v()
            self.out("%s = getelementptr inbounds %%string, ptr %s, i32 0, i32 1" % (p, src))
            x = self.v()
            self.out("%s = load i64, ptr %s" % (x, p))
            self.out("%s = xor i64 %s, %s" % (r, a, x))
        self.out("store i64 %s, ptr %s" % (r, self.int_local()))

    def ev_builtin(self, runtime):
        if runtime:  # make/append: a runtime call that cannot unwind
            n = self.load_int()
            p = self.v()
            self.out("%s = call ptr @gopp.makeslice(i64 %s)" % (p, n))
            self.out("store ptr %s, ptr @gslice" % p)
        else:  # len(s): an inline load
            _, ln = self.string_arg()
            self.out("store i64 %s, ptr %s" % (ln, self.int_local()))

    def ev_owner(self):
        o = "%%o%d" % self.n_owners
        a, al = self.string_arg()
        b, bl = self.string_arg()
        self.out("call void @gopp.string.concat(ptr %s, ptr %s, i64 %s, ptr %s, i64 %s)" % (o, a, al, b, bl))
        self.owners.append(self.n_owners)
        self.scopes[-1].append(self.n_owners)
        self.n_owners += 1

    # -- the function --------------------------------------------------------
    def landing_pad(self, name):
        """Starts a pad block; returns nothing, stores exn/selector."""
        self.block(name)
        if self.mode == "eh":
            lp = self.v()
            self.out("%s = landingpad { ptr, i32 }" % lp)
            self.out("        cleanup")
            e = self.v()
            self.out("%s = extractvalue { ptr, i32 } %s, 0" % (e, lp))
            s = self.v()
            self.out("%s = extractvalue { ptr, i32 } %s, 1" % (s, lp))
        else:
            e, s = "null", "0"
        self.out("store ptr %s, ptr %%exn.slot" % e)
        self.out("store i32 %s, ptr %%ehsel.slot" % s)
        self.st["pads"] += 1

    def resume(self):
        e = self.v()
        self.out("%s = load ptr, ptr %%exn.slot" % e)
        s = self.v()
        self.out("%s = load i32, ptr %%ehsel.slot" % s)
        if self.mode == "eh":
            a = self.v()
            self.out("%s = insertvalue { ptr, i32 } poison, ptr %s, 0" % (a, e))
            b = self.v()
            self.out("%s = insertvalue { ptr, i32 } %s, i32 %s, 1" % (b, a, s))
            self.out("resume { ptr, i32 } %s" % b)
        else:
            self.out("call void @gopp.fake.resume(ptr %s, i32 %s)" % (e, s))
            self.out("unreachable")

    def drop_all(self, owners, temps):
        for i in reversed(range(temps)):
            self.out("call void @gopp.string.drop(ptr %%tmp%d)" % i)
        for i in reversed(range(owners)):
            self.out("call void @gopp.string.drop(ptr %%o%d)" % i)

    def emit(self, f, rng):
        self.f, self.rng = f, rng
        self.nv = self.nl = 0
        self.owners = []  # live owners, innermost last
        self.scopes = [[]]  # owners declared in each open block
        self.n_owners = 0
        self.ntemps = 0
        self.lpads, self.chains = {}, {}
        self.temp_pads = []
        self.shared = {}
        self.need_single = False
        self.states = {}  # --pads state: cleanup block -> state index
        self.body = []
        n_owners = sum(1 for e in f.events if e[0] == "owner")
        n_temps = sum(1 for e in f.events if e[0] == "call" and e[2] and self.fns[e[1]].nstr)
        self.nints = max(2, min(8, f.lines // 3))
        ret, _ = self.sig(f)
        names = []
        if self.abi == "split" and f.ret in ("terr", "pair"):
            names.append("ptr %out")
        for k in range(f.nstr):
            names += ["ptr %%s%d.p" % k, "i64 %%s%d.n" % k]
        for k in range(f.nint):
            names.append("i64 %%a%d" % k)
        if f.pair_param:
            names += ["%pair %pp"] if self.abi == "agg" else ["i64 %pp.0", "i64 %pp.1"]
        attrs = " nounwind uwtable" if self.mode == "noeh" else " uwtable"

        # entry: allocas, parameter spills, zeroed owners (O0 style)
        ent = ["entry:"]
        for k in range(self.nints):
            ent.append("  %%i%d = alloca i64" % k)
        for k in range(f.nstr):
            ent.append("  %%sp%d = alloca %%string" % k)
        for k in range(n_owners):
            ent.append("  %%o%d = alloca %%string" % k)
        for k in range(n_temps):
            ent.append("  %%tmp%d = alloca %%string" % k)
        ent += ["  %if = alloca %iface", "  %outt = alloca %terr", "  %outp = alloca %pair",
                "  %ret.val = alloca i64", "  %ret.itab = alloca ptr", "  %ret.data = alloca ptr",
                "  %exn.slot = alloca ptr", "  %ehsel.slot = alloca i32"]
        if self.pads == "state":
            ent.append("  %eh.state = alloca i32")
        if self.panics == "shared":
            ent += ["  %pslot0 = alloca i64", "  %pslot1 = alloca i64"]
        for k in range(f.nstr):
            ent.append("  %%sp%d.f0 = getelementptr inbounds %%string, ptr %%sp%d, i32 0, i32 0" % (k, k))
            ent.append("  store ptr %%s%d.p, ptr %%sp%d.f0" % (k, k))
            ent.append("  %%sp%d.f1 = getelementptr inbounds %%string, ptr %%sp%d, i32 0, i32 1" % (k, k))
            ent.append("  store i64 %%s%d.n, ptr %%sp%d.f1" % (k, k))
        for k in range(f.nint):
            ent.append("  store i64 %%a%d, ptr %%i%d" % (k, k % self.nints))
        if f.pair_param:
            if self.abi == "agg":
                ent.append("  %pp.0 = extractvalue %pair %pp, 0")
                ent.append("  %pp.1 = extractvalue %pair %pp, 1")
            ent.append("  store i64 %pp.0, ptr %i0")
            ent.append("  store i64 %pp.1, ptr %i1")
        for k in range(f.nint, self.nints):
            # from memory the optimizer cannot see through, so an `opt 0`
            # pipeline does not fold the program away
            ent.append("  %%seed%d = load i64, ptr @gopp.seed" % k)
            ent.append("  store i64 %%seed%d, ptr %%i%d" % (k, k))
        ent.append("  call void @llvm.memcpy.p0.p0.i64(ptr %if, ptr @gopp.seedif, i64 16, i1 false)")
        for k in range(n_owners):
            ent.append("  call void @llvm.memset.p0.i64(ptr %%o%d, i8 0, i64 24, i1 false)" % k)
        for k in range(n_temps):
            ent.append("  call void @llvm.memset.p0.i64(ptr %%tmp%d, i8 0, i64 24, i1 false)" % k)
        ent += ["  store i64 0, ptr %ret.val", "  store ptr null, ptr %ret.itab", "  store ptr null, ptr %ret.data"]
        if self.mode == "shape":
            ent.append("  %fake = load i1, ptr @gopp.fake")
        ent.append("  br label %body")

        pads_before = self.st["pads"]
        self.block("body")
        stack = []  # open control flow: ("if", end) or ("loop", head, end)
        for e in f.events:
            kind = e[0]
            if kind == "if":
                c = self.v()
                x = self.load_int()
                self.out("%s = icmp sgt i64 %s, %d" % (c, x, rng.randrange(50)))
                then, end = self.label("then"), self.label("endif")
                self.out("br i1 %s, label %%%s, label %%%s" % (c, then, end))
                self.block(then)
                stack.append(("if", end))
                self.scopes.append([])
            elif kind == "loop":
                hd, bd, end = self.label("for.head"), self.label("for.body"), self.label("for.end")
                self.out("br label %%%s" % hd)
                self.block(hd)
                x = self.load_int()
                c = self.v()
                self.out("%s = icmp slt i64 %s, %d" % (c, x, rng.randrange(8, 64)))
                self.out("br i1 %s, label %%%s, label %%%s" % (c, bd, end))
                self.block(bd)
                stack.append(("loop", hd, end))
                self.scopes.append([])
            elif kind == "end":
                top = stack.pop()
                for o in reversed(self.scopes.pop()):  # end of block: drop
                    self.out("call void @gopp.string.drop(ptr %%o%d)" % o)
                    self.owners.remove(o)
                if top[0] == "if":
                    self.out("br label %%%s" % top[1])
                    self.block(top[1])
                else:
                    x = self.load_int()
                    y = self.v()
                    self.out("%s = add i64 %s, 1" % (y, x))
                    self.out("store i64 %s, ptr %s" % (y, self.int_local()))
                    self.out("br label %%%s" % top[1])
                    self.block(top[2])
            elif kind == "owner":
                self.ev_owner()
            elif kind == "call":
                self.ev_call(e[1], e[2] and self.fns[e[1]].nstr > 0)
            elif kind == "ncall":
                x = self.load_int()
                r = self.v()
                self.out("%s = call i64 @leaf%d(i64 %s)" % (r, e[1], x))
                self.out("store i64 %s, ptr %s" % (r, self.int_local()))
                self.st["calls_nounwind"] += 1
            elif kind == "builtin":
                self.ev_builtin(e[1])
            elif kind == "bounds":
                self.ev_bounds()
            elif kind in ("assert", "nil"):
                self.ev_iface_check(kind)
            elif kind == "div":
                self.ev_div()
            elif kind == "plain":
                self.ev_plain(e[1])
        x = self.load_int()
        self.out("store i64 %s, ptr %%ret.val" % x)
        self.out("br label %exit")

        # exit: run the deferred call, drop every owner, return
        self.block("exit")
        if f.has_defer:  # a panic in it still drops the owners
            if self.mode == "eh":
                self.out("invoke void @f%d()" % self.defer_target())
                self.out("        to label %exit.ran unwind label %dexit")
            elif self.mode == "shape":
                self.out("call void @f%d()" % self.defer_target())
                self.out("br i1 %fake, label %dexit, label %exit.ran")
            else:
                self.out("call void @f%d()" % self.defer_target())
                self.out("br label %exit.ran")
            self.block("exit.ran")
        self.drop_all(n_owners, n_temps)
        self.ret(f)

        self.shared_panics()
        # landing pads
        if self.mode != "noeh":
            if f.has_defer:
                self.defer_pads(n_owners, n_temps)
                self.landing_pad("dexit")
                self.drop_all(n_owners, n_temps)
                self.resume()
            elif self.states:
                self.landing_pad("lpad.state")
                st = self.v()
                self.out("%s = load i32, ptr %%eh.state" % st)
                # compare and branch, not `switch`: FastISel cannot select a
                # switch and would hand the block to SelectionDAG
                targets = sorted(self.states, key=self.states.get)
                for t in targets[1:]:
                    c = self.v()
                    self.out("%s = icmp eq i32 %s, %d" % (c, st, self.states[t]))
                    nxt = self.label("lpad.next")
                    self.out("br i1 %s, label %%%s, label %%%s" % (c, t, nxt))
                    self.block(nxt)
                self.out("br label %%%s" % targets[0])
                for name, tmp, chain in self.temp_pads:
                    self.block(name)
                    self.out("call void @gopp.string.drop(ptr %s)" % tmp)
                    self.out("br label %%%s" % chain)
                self.emit_chains()
            elif self.need_single:
                self.landing_pad("lpad.all")
                self.drop_all(n_owners, n_temps)
                self.resume()
            else:
                for name, tmp, chain in self.temp_pads:
                    self.landing_pad(name)
                    self.out("call void @gopp.string.drop(ptr %s)" % tmp)
                    self.out("br label %%%s" % chain)
                for chain, name in self.lpads.items():
                    self.landing_pad(name)
                    self.out("br label %%%s" % chain)
                self.emit_chains()
        has_pads = self.mode == "eh" and self.st["pads"] > pads_before
        pers = " personality ptr @__gxx_personality_v0" if has_pads else ""
        head = "define %s @f%d(%s)%s%s {" % (ret, f.idx, ", ".join(names), attrs, pers)
        return [head] + ent + self.body + ["}", ""]

    def emit_chains(self):
        for live, name in sorted(self.chains.items(), key=lambda kv: -len(kv[0])):
            self.block(name)
            if live:
                self.out("call void @gopp.string.drop(ptr %%o%d)" % live[-1])
                self.out("br label %%%s" % self.chains[live[:-1]])
            else:
                self.resume()

    def defer_target(self):
        """The deferred call: a void, parameterless function."""
        return self.void0[self.f.idx % len(self.void0)]

    def defer_pads(self, n_owners, n_temps):
        """Catch-all: run the deferred call, recover or rethrow (D4.6)."""
        self.block("dpad")
        if self.mode == "eh":
            lp = self.v()
            self.out("%s = landingpad { ptr, i32 }" % lp)
            self.out("        catch ptr null")
            e = self.v()
            self.out("%s = extractvalue { ptr, i32 } %s, 0" % (e, lp))
        else:
            e = "null"
        self.st["pads"] += 1
        obj = self.v()
        self.out("%s = call ptr @__cxa_begin_catch(ptr %s)" % (obj, e))
        # a panic inside the deferred call ends the catch and keeps unwinding
        if self.mode == "eh":
            self.out("invoke void @f%d()" % self.defer_target())
            self.out("        to label %dran unwind label %dnested")
        else:
            self.out("call void @f%d()" % self.defer_target())
            self.out("br i1 %fake, label %dnested, label %dran")
        self.block("dran")
        r = self.v()
        self.out("%s = call i1 @gopp.recovered(ptr %s)" % (r, obj))
        self.out("br i1 %s, label %%recovered, label %%rethrow" % r)
        self.block("recovered")
        self.out("call void @__cxa_end_catch()")
        self.out("br label %exit.nodefer")
        self.block("exit.nodefer")
        self.drop_all(n_owners, n_temps)
        self.ret(self.f)
        self.block("rethrow")
        if self.mode == "eh":
            self.out("invoke void @__cxa_rethrow()")
            self.out("        to label %rethrow.unreachable unwind label %dnested")
            self.block("rethrow.unreachable")
            self.out("unreachable")
        else:
            self.out("call void @__cxa_rethrow()")
            self.out("br label %dnested")
        self.landing_pad("dnested")
        self.out("call void @__cxa_end_catch()")
        self.drop_all(n_owners, n_temps)
        self.resume()

    def ret(self, f):
        if f.ret == "void":
            self.out("ret void")
            return
        x = self.v()
        self.out("%s = load i64, ptr %%ret.val" % x)
        if f.ret == "i64":
            self.out("ret i64 %s" % x)
            return
        if self.abi == "split":
            ty = "%terr" if f.ret == "terr" else "%pair"
            p = self.v()
            self.out("%s = getelementptr inbounds %s, ptr %%out, i32 0, i32 0" % (p, ty))
            self.out("store i64 %s, ptr %s" % (x, p))
            if f.ret == "terr":
                for k, slot in ((0, "%ret.itab"), (1, "%ret.data")):
                    y = self.v()
                    self.out("%s = load ptr, ptr %s" % (y, slot))
                    q = self.v()
                    self.out("%s = getelementptr inbounds %%terr, ptr %%out, i32 0, i32 1, i32 %d" % (q, k))
                    self.out("store ptr %s, ptr %s" % (y, q))
            self.out("ret void")
            return
        if f.ret == "pair":
            a = self.v()
            self.out("%s = insertvalue %%pair poison, i64 %s, 0" % (a, x))
            b = self.v()
            self.out("%s = insertvalue %%pair %s, i64 %s, 1" % (b, a, x))
            self.out("ret %%pair %s" % b)
            return
        it, dt = self.v(), self.v()
        self.out("%s = load ptr, ptr %%ret.itab" % it)
        self.out("%s = load ptr, ptr %%ret.data" % dt)
        a, b, c = self.v(), self.v(), self.v()
        self.out("%s = insertvalue %%terr poison, i64 %s, 0" % (a, x))
        self.out("%s = insertvalue %%terr %s, ptr %s, 1, 0" % (b, a, it))
        self.out("%s = insertvalue %%terr %s, ptr %s, 1, 1" % (c, b, dt))
        self.out("ret %%terr %s" % c)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--source-lines", type=int, default=9000,
                    help="Go++ body lines to model (9000 gives about 100k IR lines)")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--mode", choices=["eh", "noeh", "shape"], default="eh")
    ap.add_argument("--abi", choices=["agg", "split"], default="agg")
    ap.add_argument("--pads", choices=["chain", "single", "state"], default="chain")
    ap.add_argument("--panics", choices=["each", "shared"], default="each")
    ap.add_argument("--triple", default="x86_64-unknown-linux-gnu")
    args = ap.parse_args()

    n_leaf = 64
    fns = make_program(random.Random(args.seed), args.source_lines, n_leaf)
    stats = {k: 0 for k in ("calls", "calls_plain", "calls_nounwind", "invokes", "live_at_invoke",
                            "panic_sites", "bounds", "pads", "struct_args", "agg_results")}
    em = Emitter(fns, args.mode, args.abi, args.pads, args.panics, stats)
    em.void0 = [f.idx for f in fns if f.ret == "void" and not f.nstr and not f.nint
                and not f.pair_param] or [0]
    eh = args.mode == "eh"
    out = [PRELUDE.format(
        triple=args.triple,
        eh_attr="" if eh else " nounwind",
        rethrow_attr=" noreturn" if eh else " noreturn nounwind",
        panic_attr=" nounwind" if args.mode == "noeh" else "")]
    for k in range(n_leaf):
        out.append("declare i64 @leaf%d(i64) nounwind" % k)
    out.append("")
    # The body of each function is drawn from its own stream, so the modes
    # render the same program.
    for f in fns:
        out += em.emit(f, random.Random(args.seed * 1000003 + f.idx))
    out.append('!0 = !{!"branch_weights", i32 2000, i32 1}')
    text = "\n".join(out) + "\n"
    sys.stdout.write(text)

    src = sum(f.lines for f in fns)
    unw = stats["calls_plain"] + stats["invokes"]
    st = stats
    sys.stderr.write(
        "functions %d, source lines %d, IR lines %d\n" % (len(fns), src, text.count("\n")) +
        "per 100 source lines: calls %.1f (+%.1f nounwind), bounds %.1f, panic sites %.1f\n"
        % (100 * st["calls"] / src, 100 * st["calls_nounwind"] / src, 100 * st["bounds"] / src,
           100 * st["panic_sites"] / src) +
        "unwinding sites (calls + panics) %d, as invoke %d (%.0f%%), owners live at an invoke %.2f\n"
        % (unw, st["invokes"], 100 * st["invokes"] / max(1, unw), st["live_at_invoke"] / max(1, st["invokes"])) +
        "landing pads %d, small struct args %d, aggregate results %d, functions with defer %d\n"
        % (st["pads"], st["struct_args"], st["agg_results"], sum(f.has_defer for f in fns)))


if __name__ == "__main__":
    main()
